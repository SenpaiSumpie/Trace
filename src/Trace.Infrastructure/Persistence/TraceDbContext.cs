using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Pgvector;
using Trace.Domain;

namespace Trace.Infrastructure.Persistence;

public sealed class TraceDbContext(DbContextOptions<TraceDbContext> options, TimeProvider timeProvider)
    : DbContext(options)
{
    internal const string InvestigationIdempotencyIndex = "ux_investigations_idempotency_key";

    internal const string ActiveSnapshotKeyIndex = "ux_index_snapshots_active_key";

    private const string Sha256Hex = "'^[0-9a-f]{64}$'";

    public DbSet<Repository> Repositories => Set<Repository>();

    public DbSet<IndexSnapshot> IndexSnapshots => Set<IndexSnapshot>();

    public DbSet<SourceChunk> SourceChunks => Set<SourceChunk>();

    public DbSet<Investigation> Investigations => Set<Investigation>();

    public DbSet<InvestigationEvent> InvestigationEvents => Set<InvestigationEvent>();

    public DbSet<EvidenceRef> EvidenceRefs => Set<EvidenceRef>();

    public DbSet<Job> Jobs => Set<Job>();

    internal static void Configure(DbContextOptionsBuilder builder, string connectionString) =>
        builder.UseNpgsql(connectionString, npgsql => npgsql.UseVector()).UseSnakeCaseNamingConvention();

    public override int SaveChanges(bool acceptAllChangesOnSuccess)
    {
        StampTimestamps();
        return base.SaveChanges(acceptAllChangesOnSuccess);
    }

    public override Task<int> SaveChangesAsync(
        bool acceptAllChangesOnSuccess,
        CancellationToken cancellationToken = default)
    {
        StampTimestamps();
        return base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken);
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.HasPostgresExtension("vector");

        modelBuilder.Entity<Repository>(ConfigureRepository);
        modelBuilder.Entity<IndexSnapshot>(ConfigureIndexSnapshot);
        modelBuilder.Entity<SourceChunk>(ConfigureSourceChunk);
        modelBuilder.Entity<Investigation>(ConfigureInvestigation);
        modelBuilder.Entity<InvestigationEvent>(ConfigureInvestigationEvent);
        modelBuilder.Entity<EvidenceRef>(ConfigureEvidenceRef);
        modelBuilder.Entity<Job>(ConfigureJob);

        // IDs are generated by the domain (UUIDv7), never by the database.
        foreach (var entityType in modelBuilder.Model.GetEntityTypes())
        {
            entityType.FindProperty(nameof(Entity.Id))!.ValueGenerated =
                Microsoft.EntityFrameworkCore.Metadata.ValueGenerated.Never;
        }
    }

    private static void ConfigureRepository(EntityTypeBuilder<Repository> repository)
    {
        repository.ToTable("repositories", table => table.HasCheckConstraint(
            "ck_repositories_visibility", EnumStorage.CheckSql<RepositoryVisibility>("visibility")));

        repository.Property(r => r.Owner).HasMaxLength(Repository.MaxNameLength);
        repository.Property(r => r.Name).HasMaxLength(Repository.MaxNameLength);
        repository.Property(r => r.DefaultBranch).HasMaxLength(Repository.MaxBranchLength);
        repository.Property(r => r.Visibility).HasMaxLength(20).HasConversion(
            value => EnumStorage.ToStorage(value),
            stored => EnumStorage.FromStorage<RepositoryVisibility>(stored));
        repository.Property(r => r.GitHubRepoId).HasColumnName("github_repo_id");

        repository.HasIndex(r => r.GitHubRepoId).IsUnique();
    }

    private static void ConfigureIndexSnapshot(EntityTypeBuilder<IndexSnapshot> snapshot)
    {
        snapshot.ToTable("index_snapshots", table =>
        {
            table.HasCheckConstraint(
                "ck_index_snapshots_status", EnumStorage.CheckSql<SnapshotStatus>("status"));
            table.HasCheckConstraint(
                "ck_index_snapshots_commit_sha", "commit_sha ~ '^[0-9a-f]{40}$'");
            table.HasCheckConstraint(
                "ck_index_snapshots_completed_at", "(status = 'completed') = (completed_at IS NOT NULL)");
        });

        snapshot.Property(s => s.CommitSha).HasMaxLength(40).IsFixedLength();
        snapshot.Property(s => s.Branch).HasMaxLength(Repository.MaxBranchLength);
        snapshot.Property(s => s.ParserVersion).HasMaxLength(IndexSnapshot.MaxVersionLength);
        snapshot.Property(s => s.EmbeddingModel).HasMaxLength(IndexSnapshot.MaxVersionLength);
        snapshot.Property(s => s.Status).HasMaxLength(20).HasConversion(
            value => EnumStorage.ToStorage(value),
            stored => EnumStorage.FromStorage<SnapshotStatus>(stored));

        snapshot.HasOne<Repository>().WithMany()
            .HasForeignKey(s => s.RepositoryId)
            .OnDelete(DeleteBehavior.Cascade);

        // Target of the investigations foreign key that keeps a pinned snapshot in its own repository.
        snapshot.HasAlternateKey(s => new { s.Id, s.RepositoryId });

        // At most one building or completed snapshot per (repository, commit, parser, model):
        // re-indexing the same inputs is idempotent, while a failed attempt can be retried.
        snapshot.HasIndex(s => new { s.RepositoryId, s.CommitSha, s.ParserVersion, s.EmbeddingModel })
            .IsUnique()
            .HasFilter("status <> 'failed'")
            .HasDatabaseName(ActiveSnapshotKeyIndex);
    }

    private static void ConfigureSourceChunk(EntityTypeBuilder<SourceChunk> chunk)
    {
        chunk.ToTable("source_chunks", table =>
        {
            table.HasCheckConstraint(
                "ck_source_chunks_line_range", "start_line >= 1 AND end_line >= start_line");
            table.HasCheckConstraint(
                "ck_source_chunks_content_hash", $"content_hash ~ {Sha256Hex}");
            table.HasCheckConstraint(
                "ck_source_chunks_text_length",
                $"char_length(text) BETWEEN 1 AND {SourceChunk.MaxTextLength}");
        });

        chunk.Property(c => c.Path).HasMaxLength(SourceChunk.MaxPathLength);
        chunk.Property(c => c.Language).HasMaxLength(SourceChunk.MaxLanguageLength);
        chunk.Property(c => c.ContentHash).HasMaxLength(64).IsFixedLength();
        chunk.Property(c => c.Embedding)
            .HasColumnType($"vector({SourceChunk.EmbeddingDimensions})")
            .HasConversion(
                values => new Vector(values),
                vector => vector.ToArray(),
                new ValueComparer<float[]>(
                    (left, right) => left!.SequenceEqual(right!),
                    values => values.Length,
                    values => values));

        chunk.HasOne<IndexSnapshot>().WithMany()
            .HasForeignKey(c => c.SnapshotId)
            .OnDelete(DeleteBehavior.Cascade);

        // Target of the evidence foreign key that keeps a cited chunk in the investigation's snapshot.
        chunk.HasAlternateKey(c => new { c.Id, c.SnapshotId });

        chunk.HasIndex(c => new { c.SnapshotId, c.Path, c.StartLine, c.EndLine }).IsUnique();
    }

    private static void ConfigureInvestigation(EntityTypeBuilder<Investigation> investigation)
    {
        investigation.ToTable("investigations", table =>
        {
            table.HasCheckConstraint(
                "ck_investigations_type", EnumStorage.CheckSql<InvestigationType>("type"));
            table.HasCheckConstraint(
                "ck_investigations_state", EnumStorage.CheckSql<InvestigationState>("state"));
        });

        investigation.Property(i => i.Question).HasMaxLength(Investigation.MaxQuestionLength);
        investigation.Property(i => i.ResultJson).HasColumnType("jsonb");
        investigation.Property(i => i.IdempotencyKey).HasMaxLength(Investigation.MaxIdempotencyKeyLength);
        investigation.Property(i => i.ModelId).HasMaxLength(Investigation.MaxVersionLength);
        investigation.Property(i => i.PromptVersion).HasMaxLength(Investigation.MaxVersionLength);
        investigation.Property(i => i.ErrorCode).HasMaxLength(Investigation.MaxErrorCodeLength);

        // A repeated request with the same key must not create a second investigation.
        investigation.HasIndex(i => new { i.RepositoryId, i.IdempotencyKey })
            .IsUnique()
            .HasFilter("idempotency_key IS NOT NULL")
            .HasDatabaseName(InvestigationIdempotencyIndex);
        investigation.Property(i => i.Type).HasMaxLength(20).HasConversion(
            value => EnumStorage.ToStorage(value),
            stored => EnumStorage.FromStorage<InvestigationType>(stored));
        investigation.Property(i => i.State).HasMaxLength(20).HasConversion(
            value => EnumStorage.ToStorage(value),
            stored => EnumStorage.FromStorage<InvestigationState>(stored));

        investigation.HasOne<Repository>().WithMany()
            .HasForeignKey(i => i.RepositoryId)
            .OnDelete(DeleteBehavior.Cascade);

        // Composite key: the pinned snapshot must belong to the investigation's repository.
        // NoAction: a snapshot that investigations cite cannot be deleted on its own.
        investigation.HasOne<IndexSnapshot>().WithMany()
            .HasForeignKey(i => new { i.SnapshotId, i.RepositoryId })
            .HasPrincipalKey(s => new { s.Id, s.RepositoryId })
            .OnDelete(DeleteBehavior.NoAction);

        investigation.HasAlternateKey(i => new { i.Id, i.SnapshotId });
    }

    private static void ConfigureInvestigationEvent(EntityTypeBuilder<InvestigationEvent> investigationEvent)
    {
        investigationEvent.ToTable("investigation_events", table =>
        {
            table.HasCheckConstraint(
                "ck_investigation_events_event_type",
                EnumStorage.CheckSql<InvestigationEventType>("event_type"));
            table.HasCheckConstraint("ck_investigation_events_seq", "seq >= 1");
        });

        investigationEvent.Property(e => e.Summary).HasMaxLength(InvestigationEvent.MaxSummaryLength);
        investigationEvent.Property(e => e.ToolName).HasMaxLength(InvestigationEvent.MaxToolNameLength);
        investigationEvent.Property(e => e.MetadataJson).HasColumnType("jsonb");
        investigationEvent.Property(e => e.EventType).HasMaxLength(30).HasConversion(
            value => EnumStorage.ToStorage(value),
            stored => EnumStorage.FromStorage<InvestigationEventType>(stored));

        investigationEvent.HasOne<Investigation>().WithMany()
            .HasForeignKey(e => e.InvestigationId)
            .OnDelete(DeleteBehavior.Cascade);

        investigationEvent.HasIndex(e => new { e.InvestigationId, e.Seq }).IsUnique();
    }

    private static void ConfigureEvidenceRef(EntityTypeBuilder<EvidenceRef> evidence)
    {
        evidence.ToTable("evidence_refs", table =>
        {
            table.HasCheckConstraint(
                "ck_evidence_refs_source_kind", EnumStorage.CheckSql<EvidenceSourceKind>("source_kind"));
            table.HasCheckConstraint(
                "ck_evidence_refs_code_has_chunk", "source_kind <> 'code' OR chunk_id IS NOT NULL");
            table.HasCheckConstraint(
                "ck_evidence_refs_excerpt_hash", $"excerpt_hash ~ {Sha256Hex}");
        });

        evidence.Property(e => e.LocatorJson).HasColumnType("jsonb");
        evidence.Property(e => e.ExcerptHash).HasMaxLength(64).IsFixedLength();
        evidence.Property(e => e.SourceKind).HasMaxLength(20).HasConversion(
            value => EnumStorage.ToStorage(value),
            stored => EnumStorage.FromStorage<EvidenceSourceKind>(stored));

        // Both keys share snapshot_id, so evidence can only cite chunks from the snapshot its
        // investigation is pinned to.
        evidence.HasOne<Investigation>().WithMany()
            .HasForeignKey(e => new { e.InvestigationId, e.SnapshotId })
            .HasPrincipalKey(i => new { i.Id, i.SnapshotId })
            .OnDelete(DeleteBehavior.Cascade);

        evidence.HasOne<SourceChunk>().WithMany()
            .HasForeignKey(e => new { e.ChunkId, e.SnapshotId })
            .HasPrincipalKey(c => new { c.Id, c.SnapshotId })
            .IsRequired(false)
            .OnDelete(DeleteBehavior.NoAction);
    }

    private static void ConfigureJob(EntityTypeBuilder<Job> job)
    {
        job.ToTable("jobs", table =>
        {
            table.HasCheckConstraint("ck_jobs_status", EnumStorage.CheckSql<JobStatus>("status"));
            table.HasCheckConstraint("ck_jobs_attempts", "attempts >= 0");
        });

        job.Property(j => j.Kind).HasMaxLength(Job.MaxKindLength);
        job.Property(j => j.TenantScope).HasMaxLength(Job.MaxScopeLength);
        job.Property(j => j.DedupeKey).HasMaxLength(Job.MaxDedupeKeyLength);
        job.Property(j => j.PayloadJson).HasColumnType("jsonb");
        job.Property(j => j.ErrorCode).HasMaxLength(100);
        job.Property(j => j.Status).HasMaxLength(20).HasConversion(
            value => EnumStorage.ToStorage(value),
            stored => EnumStorage.FromStorage<JobStatus>(stored));

        job.HasIndex(j => new { j.Kind, j.DedupeKey }).IsUnique();
        job.HasIndex(j => new { j.Status, j.CreatedAt });
    }

    private void StampTimestamps()
    {
        var now = timeProvider.GetUtcNow();
        foreach (var entry in ChangeTracker.Entries<Entity>())
        {
            if (entry.State == EntityState.Added)
            {
                entry.Property(e => e.CreatedAt).CurrentValue = now;
                entry.Property(e => e.UpdatedAt).CurrentValue = now;
            }
            else if (entry.State == EntityState.Modified)
            {
                entry.Property(e => e.UpdatedAt).CurrentValue = now;
            }
        }
    }
}
